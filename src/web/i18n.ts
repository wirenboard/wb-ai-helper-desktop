import { ref } from 'vue'

export type Lang = 'ru' | 'en'
const LANG_KEY = 'wb-lang'

// Safe in non-DOM contexts (SSR / unit tests): falls back to 'ru' when no
// localStorage / navigator is available.
function detectLang(): Lang {
  try {
    const stored = typeof localStorage !== 'undefined' ? (localStorage.getItem(LANG_KEY) as Lang | null) : null
    if (stored === 'ru' || stored === 'en') return stored
    const nav = typeof navigator !== 'undefined' ? navigator.language?.toLowerCase() : undefined
    if (!nav) return 'ru'
    return nav.startsWith('ru') ? 'ru' : 'en'
  } catch {
    return 'ru'
  }
}

export const lang = ref<Lang>(detectLang())
if (typeof document !== 'undefined') document.documentElement.lang = lang.value

export function setLang(l: Lang): void {
  lang.value = l
  if (typeof localStorage !== 'undefined') localStorage.setItem(LANG_KEY, l)
  if (typeof document !== 'undefined') document.documentElement.lang = l
}

export function toggleLang(): void {
  setLang(lang.value === 'ru' ? 'en' : 'ru')
}

