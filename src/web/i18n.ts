type MessageTree = typeof messages.ru

function getValue(obj: unknown, key: string): unknown {
  return key.split('.').reduce<unknown>((acc, part) => {
    if (acc && typeof acc === 'object' && part in (acc as Record<string, unknown>)) {
      return (acc as Record<string, unknown>)[part]
    }
    return undefined
  }, obj)
}

function interpolate(str: string, params?: Record<string, string | number>): string {
  if (!params) return str
  return str.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? ''))
}

export function t(key: string, params?: Record<string, string | number>): string {
  const val = getValue(messages[lang.value], key) ?? getValue(messages.ru, key)
  if (typeof val !== 'string') return key
  return interpolate(val, params)
}

/** Pick the right plural form for `n`. `key` points to an array in `plurals.*`. */
export function plural(n: number, key: keyof MessageTree['plurals']): string {
  const forms = (messages[lang.value].plurals[key] ?? messages.ru.plurals[key]) as readonly string[]
  if (lang.value === 'en') return n === 1 ? (forms[0] ?? '') : (forms[1] ?? forms[0] ?? '')
  const n10 = n % 10, n100 = n % 100
  if (n10 === 1 && n100 !== 11) return forms[0] ?? ''
  if (n10 >= 2 && n10 <= 4 && (n100 < 12 || n100 > 14)) return forms[1] ?? ''
  return forms[2] ?? ''
}

/** Format byte size with localised units. */
export function fmtSize(n: number): string {
  const u = messages[lang.value].units
  if (n < 1024) return `${n} ${u.byte}`
  if (n < 1024 * 1024) return `${(n / 1024).toFixed(1)} ${u.kb}`
  return `${(n / 1024 / 1024).toFixed(1)} ${u.mb}`
}

/** Active locale tag for Intl/`toLocaleString` calls. */
export function localeTag(): string {
  return lang.value === 'ru' ? 'ru-RU' : 'en-US'
}
